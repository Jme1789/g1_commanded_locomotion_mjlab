State_RLBase::State_RLBase(int state_mode, std::string state_string)
: FSMState(state_mode, state_string) 
{
    auto cfg = param::config["FSM"][state_string];
    auto policy_dir = param::parser_policy_dir(cfg["policy_dir"].as<std::string>());

    env = std::make_unique<isaaclab::ManagerBasedRLEnv>(
        YAML::LoadFile(policy_dir / "params" / "deploy.yaml"),
        std::make_shared<unitree::BaseArticulation<LowState_t::SharedPtr>>(FSMState::lowstate)
    );
    env->alg = std::make_unique<isaaclab::OrtRunner>(policy_dir / "exported" / "policy.onnx");

    const auto detection = param::config["FSM"]["Fallen"]["detection"];
    auto fallen_detector = std::make_shared<getup_control::FallenDetector>(
        getup_control::FallenDetectorConfig{
            detection["fallen_tilt_min_rad"].as<float>(),
            detection["confirm_duration_s"].as<double>(),
            detection["max_update_gap_s"].as<double>(),
        });
    this->registered_checks.insert(
        this->registered_checks.begin(),
        std::make_pair(
            [this, fallen_detector]()->bool {
                if (FSMState::lowstate->isTimeout()) {
                    fallen_detector->reset();
                    return false;
                }
                return fallen_detector->update(
                    this->getup_torso_tilt_rad(),
                    this->monotonic_seconds());
            },
            FSMStringMap.right.at("Fallen")
        )
    );
}

void State_RLBase::run()
{
    auto action = env->apply_external_joint_position_command(
        env->action_manager->processed_actions());
    for(int i(0); i < env->robot->data.joint_ids_map.size(); i++) {
        lowcmd->msg_.motor_cmd()[env->robot->data.joint_ids_map[i]].q() = action[i];
    }
}